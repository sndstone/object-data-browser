func TestBenchmarkGeneratedReaderSeeksAndMatchesExistingPayload(t *testing.T) {
	for _, random := range []bool{false, true} {
		for _, size := range []int{0, 1, 63, 4097, 2*1024*1024 + 17} {
			expected := benchmarkPayload("run", "exact key ", size, random)
			reader := newBenchmarkPatternReader("run", "exact key ", size, random)
			var result bytes.Buffer
			buffer := make([]byte, 193)
			if _, err := io.CopyBuffer(&result, reader, buffer); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(result.Bytes(), expected) {
				t.Fatalf("generated bytes differ for %d, random=%v", size, random)
			}
			if size > 1 {
				if _, err := reader.Seek(1, io.SeekStart); err != nil {
					t.Fatal(err)
				}
				rest, err := io.ReadAll(reader)
				if err != nil || !bytes.Equal(rest, expected[1:]) {
					t.Fatal("retry seek changed payload")
				}
			}
		}
	}
}

func TestBenchmarkPayloadCacheAndPrivateDiskSpooling(t *testing.T) {
	t.Setenv("TMPDIR", t.TempDir())
	store, err := newBenchmarkPayloadStore(map[string]interface{}{"inMemoryData": true, "dataCacheMb": 1})
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	for index := 0; index < 8; index++ {
		wg.Add(1)
		go func(index int) {
			defer wg.Done()
			reader, done, err := store.open("run", fmt.Sprint(index), 512*1024, true)
			if err != nil {
				t.Error(err)
				return
			}
			defer done()
			if _, err := io.Copy(io.Discard, reader); err != nil {
				t.Error(err)
			}
		}(index)
	}
	wg.Wait()
	if store.used != 1024*1024 || len(store.cache) != 2 {
		t.Fatalf("unbounded cache: %d bytes in %d entries", store.used, len(store.cache))
	}
	large, done, err := store.open("run", "large", 1024*1024*1024, true)
	if err != nil {
		t.Fatal(err)
	}
	defer done()
	if _, ok := large.(*benchmarkPatternReader); !ok {
		t.Fatal("large payload allocated instead of streaming")
	}
	for _, budget := range []int{-1, 513} {
		if _, err := newBenchmarkPayloadStore(map[string]interface{}{"dataCacheMb": budget}); err == nil {
			t.Fatal("unsafe cache accepted")
		}
	}
	disk, err := newBenchmarkPayloadStore(map[string]interface{}{"inMemoryData": false, "dataCacheMb": 1})
	if err != nil {
		t.Fatal(err)
	}
	reader, cleanup, err := disk.open("run", "disk", 1024*1024+7, true)
	if err != nil {
		t.Fatal(err)
	}
	file, ok := reader.(*os.File)
	if !ok {
		t.Fatal("disk mode did not spool")
	}
	info, err := file.Stat()
	if err != nil || info.Mode().Perm() != 0600 {
		t.Fatal("spool is not private")
	}
	data, err := io.ReadAll(reader)
	if err != nil || !bytes.Equal(data, benchmarkPayload("run", "disk", len(data), true)) {
		t.Fatal("spooling changed data")
	}
	if disk.used != 0 {
		t.Fatal("disk mode retained a full payload in memory")
	}
	name := file.Name()
	cleanup()
	if _, err := os.Stat(name); !os.IsNotExist(err) {
		t.Fatal("spool file remains after cleanup")
	}
}

func TestBenchmarkActualSDKRetriesAndErrorsAreCounted(t *testing.T) {
	t.Setenv("TMPDIR", t.TempDir())
	var attempts atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		data, _ := io.ReadAll(r.Body)
		if !bytes.Equal(data, bytes.Repeat([]byte("A"), 32)) {
			t.Error("SDK retry changed generated body")
		}
		switch attempts.Add(1) {
		case 1:
			xmlError(w, 500, "InternalError")
		case 2:
			w.Header().Set("ETag", `"fixture"`)
		default:
			xmlError(w, 403, "AccessDenied")
		}
	}))
	defer server.Close()
	state := checkpointTestState(t)
	state["profile"] = testProfilePayload(server.URL)
	config := asMap(state["config"])
	config["bucketName"], config["maxAttempts"], config["workloadType"] = "bucket", 2, "write-only"
	config["objectSizes"], config["concurrentThreads"] = []interface{}{32}, 1
	config["inMemoryData"], config["reducedLogging"] = false, true
	if _, err := materializeBenchmarkState(state); err != nil {
		t.Fatal(err)
	}
	if asInt(state["retryCount"]) != 1 || asInt(state["processedCount"]) != 1 {
		t.Fatalf("actual retry not counted: %v", state)
	}
	if _, err := materializeBenchmarkState(state); err != nil {
		t.Fatal(err)
	}
	metrics := asMap(asMap(state["resultSummary"])["detailMetrics"])
	if state["status"] != "failed" || asInt(metrics["errorCount"]) != 1 || asInt(metrics["retryCount"]) != 1 || attempts.Load() != 3 {
		t.Fatalf("incorrect failure/retry metrics: %v", state)
	}
	for _, line := range asStringSlice(state["liveLog"]) {
		if strings.Contains(line, " completed in ") {
			t.Fatal("reduced logging retained a success line")
		}
	}
	leftovers, err := filepath.Glob(filepath.Join(runtimeDir(), ".benchmark-payload-*"))
	if err != nil || len(leftovers) > 0 {
		t.Fatalf("payloads left after successful/failed calls: %v", leftovers)
	}
}

func TestBenchmarkReadIntegrityAndChecksumFailureMetrics(t *testing.T) {
	config := map[string]interface{}{"validateChecksum": true, "reducedLogging": true}
	plan := benchmarkOpPlan{operation: "GET", key: "key", sizeBytes: 16}
	for _, algorithm := range []string{"md5", "sha1", "sha256", "crc32", "crc32c"} {
		config["checksumAlgorithm"] = algorithm
		n, checksum, err := benchmarkReadResult(bytes.NewReader(bytes.Repeat([]byte("A"), 16)), "run", config, plan)
		if err != nil || n != 16 || checksum != "validated_success" {
			t.Fatalf("%s validation failed", algorithm)
		}
	}
	for _, size := range []int{15, 17} {
		if _, _, err := benchmarkReadResult(bytes.NewReader(make([]byte, size)), "run", config, plan); err == nil {
			t.Fatal("incorrect length accepted")
		}
	}
	state := map[string]interface{}{"config": config}
	executor := &benchmarkExecutor{getReader: func(string) (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(make([]byte, 16))), nil }}
	result, err := executeBenchmarkOperation(executor, "run", config, plan)
	if err != nil {
		t.Fatal(err)
	}
	applyBenchmarkResult(state, plan, result, 0.1)
	if asInt(state["errorCount"]) != 1 || asBool(asMapSlice(state["history"])[0]["success"]) {
		t.Fatal("checksum failure reported as success")
	}
	if len(asStringSlice(state["liveLog"])) != 1 {
		t.Fatal("reduced logging must retain validation failures")
	}
}

type testAzureCredential struct{ calls atomic.Int32 }

func (c *testAzureCredential) GetToken(_ context.Context, options policy.TokenRequestOptions) (azcore.AccessToken, error) {
	c.calls.Add(1)
	if len(options.Scopes) != 1 || options.Scopes[0] != "https://storage.azure.com/.default" {
		return azcore.AccessToken{}, fmt.Errorf("incorrect token scope")
	}
	return azcore.AccessToken{Token: "private-fixture-token", ExpiresOn: time.Now().Add(time.Hour)}, nil
}

func TestAzureIdentityUsesCachedBearerTokensAndRequiresTLS(t *testing.T) {
	credential := &testAzureCredential{}
	server := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Bearer private-fixture-token" {
			t.Error("missing bearer authorization")
		}
		if r.URL.RawQuery != "" {
			t.Error("credential escaped into URL")
		}
	}))
	defer server.Close()
	base, _ := url.Parse(server.URL)
	client := &azureClient{base: base, credential: credential, httpClient: server.Client()}
	var wg sync.WaitGroup
	for index := 0; index < 8; index++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			response, err := client.do(context.Background(), http.MethodHead, "bucket", "key", nil, nil, nil)
			if err != nil {
				t.Error(err)
			} else {
				response.Body.Close()
			}
		}()
	}
	wg.Wait()
	if credential.calls.Load() != 1 {
		t.Fatal("parallel requests did not reuse token")
	}
	client.token.ExpiresOn = time.Now()
	response, err := client.do(context.Background(), http.MethodHead, "bucket", "key", nil, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	response.Body.Close()
	if credential.calls.Load() != 2 {
		t.Fatal("expired token not refreshed")
	}
	req, _ := http.NewRequest(http.MethodHead, "http://localhost/bucket", nil)
	if err := client.sign(req, nil); err == nil {
		t.Fatal("identity token would be sent over HTTP")
	}
	if req.Header.Get("Authorization") != "" {
		t.Fatal("token exposed before TLS rejection")
	}
}

func TestRangeDownloadRejectsChangedETagBeforeReplacingLocalFile(t *testing.T) {
	for _, provider := range []string{"s3Compatible", "azureBlob"} {
		t.Run(provider, func(t *testing.T) {
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				w.Header().Set("Content-Length", "1048576")
				w.Header().Set("ETag", `"original"`)
				if r.Method == http.MethodHead {
					return
				}
				if r.Header.Get("If-Match") != `"original"` {
					t.Error("range request lost source condition")
				}
				w.Header().Set("Content-Range", "bytes 0-1048575/1048576")
				w.Header().Set("ETag", `"changed"`)
				w.WriteHeader(http.StatusPartialContent)
				_, _ = io.Copy(w, newBenchmarkPatternReader("run", "key", 1024*1024, true))
			}))
			defer server.Close()
			profile := testProfilePayload(server.URL)
			profile["endpointType"] = provider
			if provider == "azureBlob" {
				profile["secretKey"] = "Zml4dHVyZQ=="
			}
			destination := t.TempDir()
			target := filepath.Join(destination, "range.bin")
			if err := os.WriteFile(target, []byte("LOCAL"), 0600); err != nil {
				t.Fatal(err)
			}
			_, err := handleRequest(request{Method: "startDownload", Params: map[string]interface{}{
				"profile": profile, "bucketName": "bucket", "keys": []interface{}{"range.bin"},
				"destinationPath": destination, "multipartThresholdMiB": 1, "multipartChunkMiB": 1, "conflictPolicy": "replace",
			}})
			if err == nil {
				t.Fatal("changed source was accepted")
			}
			data, readErr := os.ReadFile(target)
			if readErr != nil || string(data) != "LOCAL" {
				t.Fatal("invalid range replaced existing destination")
			}
			files, readErr := os.ReadDir(destination)
			if readErr != nil || len(files) != 1 {
				t.Fatal("failed range left partial files")
			}
		})
	}
}

func TestBufferedRangeCopyPreservesBytesAtOffsets(t *testing.T) {
	file, err := os.CreateTemp(t.TempDir(), "buffered-range")
	if err != nil {
		t.Fatal(err)
	}
	defer file.Close()
	const size = 3*1024*1024 + 19
	const offset = 27
	reader := newBenchmarkPatternReader("run", "range", size, true)
	count, err := copyTransferRange(&offsetFileWriter{file: file, offset: offset}, io.LimitReader(reader, size+1))
	if err != nil || count != size {
		t.Fatalf("buffered copy failed: %d, %v", count, err)
	}
	if err := file.Sync(); err != nil {
		t.Fatal(err)
	}
	actual := make([]byte, size)
	if _, err := file.ReadAt(actual, offset); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(actual, benchmarkPayload("run", "range", size, true)) {
		t.Fatal("buffered offset copy changed bytes")
	}
}
